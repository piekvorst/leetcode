#include <stdio.h>

#define nelem(x) (sizeof(x) / sizeof((x)[0]))

int *
shortestDistanceAfterQueries
	(int cities, int **queries, int nqueries, int *mqueries, int *ndistances);

void
arrprint(int *p, int len)
{
	for (int *q = p; q != p+len; ++q)
		printf("	%d", *q);

	printf("\n");
}

void
example1(void)
{
	printf("main.c:/example1/\n");

	int *queries[] = {
		(int []){2, 4},
		(int []){0, 2},
		(int []){0, 4},
	};

	int ndistances = 0;
	int *distances = shortestDistanceAfterQueries(
		5,
		queries, nelem(queries),
		(int []){2, 2, 2},
		&ndistances
	); // 3, 2, 1

	printf("distances:\n");
	arrprint(distances, ndistances);
	printf("\n");
}

